def seed_quiz_questions():
    """Insert quiz questions that are not already present; return the number added."""
    existing_by_subject = {}
    added_count = 0

    for item in QUIZ_QUESTIONS:
        (
            subject, question, option_a, option_b, option_c, option_d,
            correct_answer, explanation, difficulty
        ) = item

        if subject not in existing_by_subject:
            existing_questions = get_quiz_questions(subject=subject)
            existing_by_subject[subject] = {
                " ".join(row[2].split()).casefold()
                for row in existing_questions
            }

        normalized_question = " ".join(question.split()).casefold()
        if normalized_question in existing_by_subject[subject]:
            continue

        add_quiz_question(
            subject, question, option_a, option_b, option_c, option_d,
            correct_answer, explanation, difficulty, "system"
        )
        existing_by_subject[subject].add(normalized_question)
        added_count += 1

    return added_count
